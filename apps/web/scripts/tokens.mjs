// Generates the web client's themes from design/tokens/*.json: CSS custom
// properties (src/generated/themes.css) and a typed table for what code needs
// (src/generated/themes.ts). Never edit the output; edit the tokens.
//
// Selectors: <html data-theme data-mode data-accent>. A theme block holds
// type, shape, material and motion; a theme+mode block the colors; a
// theme+accent block the accent. Springs become CSS linear() easings.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = join(here, "../../../design/tokens");
const out = join(here, "../src/generated");
const ids = ["glass", "swiss", "soft"];
const themes = ids.map((id) => JSON.parse(readFileSync(join(tokens, `${id}.json`), "utf8")));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const family = (list) => list.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
// Webfonts are the variable builds, registered under "<Family> Variable".
const webFamily = (list) =>
  family(list.flatMap((f, i) => (i === 0 && !/^(system-ui|sans-serif|monospace|ui-monospace)$/.test(f) ? [`${f} Variable`, f] : [f])));

/** A damped spring (SwiftUI's response/dampingFraction) as a CSS easing. */
function spring({ response, damping }) {
  const omega = (2 * Math.PI) / response;
  const position = (t) => {
    if (damping < 1) {
      const wd = omega * Math.sqrt(1 - damping * damping);
      return 1 - Math.exp(-damping * omega * t) * (Math.cos(wd * t) + ((damping * omega) / wd) * Math.sin(wd * t));
    }
    return 1 - Math.exp(-omega * t) * (1 + omega * t);
  };
  // Settled once it stays within 0.1% of rest.
  let settle = response;
  for (let t = 0; t < 10 * response; t += 0.005) {
    if (Math.abs(1 - position(t)) > 0.001) settle = t;
  }
  const samples = 48;
  const points = [];
  for (let i = 0; i <= samples; i++) points.push(+position((settle * i) / samples).toFixed(4));
  points[samples] = 1;
  return { durationMs: Math.round(settle * 1000), easing: `linear(${points.join(", ")})` };
}

function motion(entry) {
  if (entry.type === "none") return { durationMs: 0, easing: "linear" };
  if (entry.type === "spring") return spring(entry);
  if (entry.type === "timing") return { durationMs: entry.durationMs, easing: `cubic-bezier(${entry.easing.join(", ")})` };
  return null;
}

function color(value) {
  return value.replace(/\{([a-zA-Z.]+)\}/g, (_, ref) => `var(--${kebab(ref.replace(".", "-"))})`);
}

let css = "/* Generated by scripts/tokens.mjs from design/tokens. Do not edit. */\n";
for (const t of themes) {
  const v = [];
  v.push(`--font-sans: ${webFamily(t.type.families.sans)}`);
  v.push(`--font-mono: ${webFamily(t.type.families.mono)}`);
  for (const [name, s] of Object.entries(t.type.scale)) {
    v.push(`--type-${name}-family: var(--font-${s.family})`);
    v.push(`--type-${name}-size: ${s.size}px`);
    v.push(`--type-${name}-weight: ${s.weight}`);
    v.push(`--type-${name}-line: ${s.lineHeight}`);
    v.push(`--type-${name}-tracking: ${s.tracking}em`);
    v.push(`--type-${name}-case: ${s.case === "upper" ? "uppercase" : "none"}`);
  }
  for (const [name, r] of Object.entries(t.shape.radius)) v.push(`--radius-${name}: ${r}px`);
  v.push(`--bubble-radius: ${t.shape.bubble.radius}px`);
  v.push(`--bubble-tail: ${t.shape.bubble.tail}px`);
  v.push(`--pressed-radius: ${t.shape.pressedRadius ?? t.shape.radius.md}px`);
  v.push(`--border: ${t.shape.borderWidth}px`);
  v.push(`--blur: ${t.material.blur}px`);
  v.push(`--saturation: ${t.material.saturation}`);
  v.push(`--ambient: ${t.material.ambientSecondary ?? "transparent"}`);
  for (const [name, entry] of Object.entries(t.motion)) {
    const m = motion(entry);
    if (!m) continue;
    v.push(`--motion-${name}-duration: ${m.durationMs}ms`);
    v.push(`--motion-${name}-easing: ${m.easing}`);
    if (entry.scale !== undefined) v.push(`--motion-${name}-scale: ${entry.scale}`);
    if (entry.fromOpacity !== undefined) v.push(`--motion-${name}-from-opacity: ${entry.fromOpacity}`);
    if (entry.fromScale !== undefined) v.push(`--motion-${name}-from-scale: ${entry.fromScale}`);
    if (entry.fromOffsetY !== undefined) v.push(`--motion-${name}-from-y: ${entry.fromOffsetY}px`);
    if (entry.fromBlur !== undefined) v.push(`--motion-${name}-from-blur: ${entry.fromBlur}px`);
  }
  css += `\n[data-theme="${t.id}"] {\n  ${v.join(";\n  ")};\n}\n`;
  for (const mode of ["light", "dark"]) {
    const c = Object.entries(t.color[mode]).map(([k, value]) => `--${kebab(k)}: ${color(value)}`);
    c.push(`--accent-ink: var(--accent-ink-${mode})`);
    c.push(`color-scheme: ${mode}`);
    css += `\n[data-theme="${t.id}"][data-mode="${mode}"] {\n  ${c.join(";\n  ")};\n}\n`;
  }
  for (const [name, a] of Object.entries(t.accents)) {
    const c = [`--accent: ${a.value}`, `--accent-on: ${a.on}`, `--accent-ink-light: ${a.ink.light}`, `--accent-ink-dark: ${a.ink.dark}`];
    css += `\n[data-theme="${t.id}"][data-accent="${name}"] {\n  ${c.join(";\n  ")};\n}\n`;
  }
}

const table = themes.map((t) => ({
  id: t.id,
  name: t.name,
  summary: t.summary,
  isDefault: t.isDefault,
  defaultAccent: t.defaultAccent,
  accents: Object.entries(t.accents).map(([id, a]) => ({ id, value: a.value })),
  components: t.components,
  ambientGlow: t.material.ambientGlow,
  haptics: Object.fromEntries(Object.entries(t.haptics).map(([name, h]) => [name, h.web ?? []])),
  scaling: Object.entries(t.haptics)
    .filter(([, h]) => h.scaleWithProgress)
    .map(([name]) => name),
}));
const hapticNames = Object.keys(themes[0].haptics);
const ts = `// Generated by scripts/tokens.mjs from design/tokens. Do not edit.
export type ThemeId = ${ids.map((id) => JSON.stringify(id)).join(" | ")};
export type Haptic = ${hapticNames.map((n) => JSON.stringify(n)).join(" | ")};
export interface Theme {
  id: ThemeId;
  name: string;
  summary: string;
  isDefault: boolean;
  defaultAccent: string;
  accents: { id: string; value: string }[];
  components: Record<string, string>;
  ambientGlow: boolean;
  haptics: Record<Haptic, number[]>;
  /** Haptics that grow with a hold's progress (scaleWithProgress). */
  scaling: Haptic[];
}
export const themes: Theme[] = ${JSON.stringify(table, null, 2)};
`;

// The full haptic patterns, for the Android app's native haptics only
// (src/app/haptics.ts); browsers get the `web` arrays above.
const pulses = Object.fromEntries(
  themes.map((t) => [
    t.id,
    Object.fromEntries(
      Object.entries(t.haptics).map(([name, h]) => [
        name,
        h.events.map((e) => ({ t: e.t, kind: e.kind, intensity: e.intensity, sharpness: e.sharpness, durationMs: e.durationMs ?? 0 })),
      ]),
    ),
  ]),
);
const nativeTs = `// Generated by scripts/tokens.mjs from design/tokens. Do not edit.
import type { Haptic, ThemeId } from "./themes";
export interface Pulse {
  t: number;
  kind: "transient" | "continuous";
  intensity: number;
  sharpness: number;
  durationMs: number;
}
export const pulses: Record<ThemeId, Record<Haptic, Pulse[]>> = ${JSON.stringify(pulses, null, 2)};
`;

mkdirSync(out, { recursive: true });
writeFileSync(join(out, "themes.css"), css);
writeFileSync(join(out, "themes.ts"), ts);
writeFileSync(join(out, "haptics.ts"), nativeTs);
console.log(`tokens: ${themes.length} themes, ${css.length} bytes of CSS`);
